"""Copy the approved SVG-derived signal raster and embed its exact bytes.

No resizing, cropping, palette conversion, PNG recompression or alpha edits occur.
The editable SVG is checked as authoring provenance; this build needs no renderer.
Authoring inputs remain outside deploy output. The generated Lua data is loaded
only by the explicit lazy illustration request, independently of control icons.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
from pathlib import Path
import struct

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE_FILE = "signal-lost-1024.png"
APPROVED_SHA256 = "9c01e023000726d7b828fbc165fc1e13497795c073984260629391237e55ddbe"
WIDTH, HEIGHT, BYTE_LENGTH = 1024, 512, 118144
VECTOR_FILE = "signal-lost.svg"
VECTOR_SHA256 = "7da22b31206eae96d2026d980e9c238c595243c0cf4263976b559fd07f366a03"
VECTOR_BYTE_LENGTH = 25249
MAX_BYTES, MAX_PIXELS = 1048576, 2000000


def approved_source(root: Path) -> tuple[bytes, str]:
    directory = root / "artwork/ui/signal-lost"
    manifest = directory / "source-manifest.json"
    if directory.is_symlink() or not directory.resolve().is_relative_to(root.resolve()):
        raise ValueError("Approved signal artwork directory escapes the project")
    if manifest.is_symlink() or not manifest.is_file() or manifest.stat().st_size > 16384:
        raise ValueError("Invalid approved signal artwork manifest")
    raw = manifest.read_bytes()
    record = json.loads(raw)
    expected = {"file": SOURCE_FILE, "sha256": APPROVED_SHA256,
                "width": WIDTH, "height": HEIGHT, "bytes": BYTE_LENGTH, "mode": "RGBA", "alphaExtrema": [0, 255]}
    expected_vector = {"file": VECTOR_FILE, "sha256": VECTOR_SHA256, "bytes": VECTOR_BYTE_LENGTH,
                       "width": 1774, "height": 887, "viewBox": [0, 0, 1774, 887]}
    if (not isinstance(record, dict) or record.get("schemaVersion") != 2 or record.get("illustrationId") != "signal_lost"
            or record.get("source") != expected or record.get("vectorReference") != expected_vector):
        raise ValueError("Signal artwork does not match the approved source")
    vector_path = directory / VECTOR_FILE
    if (vector_path.is_symlink() or not vector_path.is_file()
            or not vector_path.resolve().is_relative_to(directory.resolve())):
        raise ValueError("Invalid approved signal SVG path")
    if vector_path.stat().st_size != VECTOR_BYTE_LENGTH:
        raise ValueError("Approved signal SVG size changed")
    if hashlib.sha256(vector_path.read_bytes()).hexdigest() != VECTOR_SHA256:
        raise ValueError("Approved signal SVG digest changed")
    path = directory / SOURCE_FILE
    if path.is_symlink() or not path.is_file() or not path.resolve().is_relative_to(directory.resolve()):
        raise ValueError("Invalid approved signal PNG path")
    if path.stat().st_size != BYTE_LENGTH or BYTE_LENGTH > MAX_BYTES:
        raise ValueError("Approved signal PNG size changed")
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != APPROVED_SHA256:
        raise ValueError("Approved signal PNG digest changed")
    if data[:8] != b"\x89PNG\r\n\x1a\n" or data[16:29] != struct.pack(">IIBBBBB", WIDTH, HEIGHT, 8, 6, 0, 0, 0):
        raise ValueError("Approved signal PNG must retain its RGBA8 canvas")
    with Image.open(io.BytesIO(data)) as image:
        image.load()
        if image.format != "PNG" or image.mode != "RGBA" or image.size != (WIDTH, HEIGHT) or WIDTH * HEIGHT > MAX_PIXELS:
            raise ValueError("Approved signal PNG format/dimensions changed")
        alpha = image.getchannel("A")
        if alpha.getextrema() != (0, 255) or sum(alpha.histogram()[1:255]) == 0:
            raise ValueError("Approved signal PNG must retain genuine partial alpha")
    return data, hashlib.sha256(raw).hexdigest()


def outputs(root: Path = ROOT) -> dict[Path, bytes]:
    data, source_hash = approved_source(root)
    directory = root / "src/PaintManager/Assets/UI/Illustrations"
    manifest = {"schemaVersion": 1, "artworkSourceSha256": source_hash,
                "illustrations": {"signal_lost": {"file": "signal_lost.png", "sha256": APPROVED_SHA256,
                    "width": WIDTH, "height": HEIGHT, "bytes": len(data), "alphaExtrema": [0, 255]}}}
    lines = ["-- Generated by tools/build_signal_art.py from the SVG-derived transparent PNG.",
             "-- Required only for a lazy signal illustration request; control startup does not load this table.",
             "return {", f"    width = {WIDTH},", f"    height = {HEIGHT},", f"    bytes = {len(data)},",
             f'    sha256 = "{APPROVED_SHA256}",', f'    hex = "{data.hex()}",', "}"]
    return {directory / "signal_lost.png": data,
            directory / "manifest.json": (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode("utf-8"),
            root / "src/PaintManager/Scripts/paintmanager/ui_signal_data.lua": ("\n".join(lines) + "\n").encode("ascii")}


def build(root: Path = ROOT, check: bool = False) -> None:
    for path, data in outputs(root).items():
        if check:
            if not path.is_file() or path.read_bytes() != data:
                raise ValueError(f"Signal artwork differs from its approved source: {path.relative_to(root)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    build(check=parser.parse_args().check)
